"""English text for the demos' text images, from the translators' documents.

GameDocuments/VictoryQuotes.md (the victory demo's quotes) and
GameDocuments/EventText.md (story events and endings) give each image's path
and, in the ```text block after it, the English. This writes them as entries
of data/locale/en/images.lton (src/locale.lh) between the GENERATED markers,
replacing what an earlier run wrote there; everything else in the file is
kept. See TechnicalDocuments/0144.

Run from the repository root with Pillow (it measures the lines in the same
fonts and samples the speakers' name colours from the original images):

    build/asset-builder-venv/Scripts/python.exe tools/locale/build_en_text.py
"""
import re
from collections import Counter
from pathlib import Path

from PIL import Image, ImageFont

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / 'data/locale/en/images.lton'
BEGIN = '# BEGIN GENERATED by tools/locale/build_en_text.py: edit the documents and run it again.'
END = '# END GENERATED'
SCREEN = 640
MARGIN = 4                       # kept between a block and the screen's edge

REGULAR = 'data/montserrat/Montserrat-Regular.ttf'
TITLE = 'data/Playfair_Display/static/PlayfairDisplay-BoldItalic.ttf'
NARRATION = 'data/Playfair_Display/static/PlayfairDisplay-Italic.ttf'

# demo -> how its text is set (see place())
VICTORY = 'ゆい勝ち'
SPEAKERS = {'エンディング0', 'エンディング２'}
NARRATED = {('エンディング0', 20), ('エンディング0', 21), ('エンディング0', 22)}
TITLES = {('ランダムかえで', 9), ('丘イベント', 9)}


def translations(doc):
    """(demo, image number, English lines) for every image with a text block."""
    out = []
    current = None
    lines = (ROOT / doc).read_text(encoding='utf-8').split('\n')
    i = 0
    while i < len(lines):
        m = re.search(r'assets.demos.([^\\/]+).images.(\d{4})\.png$', lines[i])
        if m:
            current = (m.group(1), int(m.group(2)))
        if lines[i].startswith('```text') and current is not None:
            j = i + 1
            body = []
            while not lines[j].startswith('```'):
                body.append(lines[j])
                j += 1
            if any(l.strip() for l in body):
                out.append((current[0], current[1], body))
            current = None
            i = j
        i += 1
    return out


def listing(demo):
    entries = [l for l in (ROOT / f'data/demos/{demo}/images.lton').read_text(encoding='utf-8').split('\n')
               if l.startswith('{') or l.startswith('nil')]
    return entries


def size_and_file(demo, n):
    e = listing(demo)[n]
    m = re.search(r'file = "([^"]+)", width = (\d+), height = (\d+)', e)
    return m.group(1), int(m.group(2)), int(m.group(3))


def first_x(demo):
    """Each image's first I block x in the demo's script (its layers sit at 0)."""
    txt = (ROOT / f'data/demos/{demo}/script.lton').read_text(encoding='utf-8')
    xs = {}
    for m in re.finditer(r'\{ "I", (\d+), \d+, (-?\d+), (-?\d+), "[^"]*" \}', txt):
        n, x, y = map(int, m.groups())
        if y < 1000:                 # far off screen: a preload, not where it shows
            xs.setdefault(n, x)
    return xs


def name_colour(demo, n):
    """The speaker name's colour: the bright, not white colour at the image's left."""
    file, w, h = size_and_file(demo, n)
    im = Image.open(ROOT / f'assets/demos/{demo}/{file}').convert('RGBA')
    left = im.crop((0, 0, min(64, w), min(20, h)))
    colours = Counter(p[:3] for p in left.get_flattened_data()
                      if p[3] > 200 and sum(p[:3]) > 450 and not (min(p[:3]) > 235))
    if not colours:
        return (1, 1, 1)
    r, g, b = colours.most_common(1)[0][0]
    return (round(r / 255, 3), round(g / 255, 3), round(b / 255, 3))


def lton_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def colour(c):
    return '{ ' + ', '.join(str(v) for v in c) + ' }'


def entry(demo, n, lines_lton, size, rect, align, offset, font, font_size, leading, extra=''):
    return (f'["assets/demos/{demo}/images/{n:04d}.png"] = {{\n'
            f'    lines = {{\n{lines_lton}    }},\n'
            f'    leading = {leading}, weight = 2,{extra}\n'
            f'    size = {{ {size[0]}, {size[1]} }}, rect = {{ {rect[0]}, {rect[1]}, {rect[2]}, {rect[3]} }}, align = "{align}", valign = "top",\n'
            f'    offset = {{ {offset[0]}, {offset[1]} }},\n'
            f'    font = "{font}", fontSize = {font_size},\n'
            f'    color = {{ 1, 1, 1 }}, outline = {{ color = {{ 0, 0, 0 }}, width = 1 }},\n'
            f'}},\n')


def place(demo, n, body, xs):
    _, ow, oh = size_and_file(demo, n)
    x = xs.get(n, (SCREEN - ow) // 2)
    if (demo, n) in TITLES:
        font_file, size, leading, extra = TITLE, 20, 4, ' underline = true^,'
    elif (demo, n) in NARRATED:
        font_file, size, leading, extra = NARRATION, 15, 8, ''
    elif demo == VICTORY:
        font_file, size, leading, extra = REGULAR, 14, 6, ''
    else:
        font_file, size, leading, extra = REGULAR, 14, 8, ''
    font = ImageFont.truetype(str(ROOT / font_file), size)
    line_h = font.getbbox('Ag')[3] + 4
    h = len(body) * line_h + (len(body) - 1) * leading + 8

    if demo in SPEAKERS and (demo, n) not in NARRATED:
        # "Name: text": the name in the original's colour, later lines under the text.
        first = body[0]
        name, sep, rest = first.partition(': ')
        if sep:
            indent = round(font.getlength(name + sep))
            runs = [f'{{ runs = {{ {{ text = {lton_string(name + sep)}, color = {colour(name_colour(demo, n))} }}, {{ text = {lton_string(rest)} }} }} }}']
            runs += [f'{{ text = {lton_string(l)}, indent = {indent} }}' for l in body[1:]]
        else:
            runs = [f'{{ text = {lton_string(l)} }}' for l in body]
        lines_lton = ''.join(f'        {r},\n' for r in runs)
        width = SCREEN - MARGIN - x
        return entry(demo, n, lines_lton, (width, h), (0, 2, width, h - 4), 'left', (0, -2), font_file, size, leading, extra)

    widest = round(max(font.getlength(l) for l in body)) + 10
    if (demo, n) in TITLES:
        widest = max(widest, ow)         # the underline spans the original's width
    block = min(widest, SCREEN - 2 * MARGIN)
    lines_lton = ''.join(f'        {{ text = {lton_string(l)} }},\n' for l in body)
    if demo == VICTORY:
        centre = SCREEN // 2             # every quote sits at the screen's middle
    else:
        centre = x + ow // 2             # where the original is centred
    left = centre - block // 2
    left += max(0, MARGIN - left) - max(0, left + block - (SCREEN - MARGIN))
    # The canvas spans the screen; it is moved so that its x 0 is the screen's.
    return entry(demo, n, lines_lton, (SCREEN, h), (left, 2, block, h - 4), 'left' if demo == VICTORY or len(body) > 1 else 'center',
                 (-x, -2), font_file, size, leading, extra)


def main():
    items = translations('GameDocuments/VictoryQuotes.md') + translations('GameDocuments/EventText.md')
    xs = {}
    parts = [BEGIN, '#',
             '# The demos\' text: victory quotes (GameDocuments/VictoryQuotes.md) and story',
             '# events and endings (GameDocuments/EventText.md), English by the user.', '']
    for demo, n, body in items:
        if demo not in xs:
            xs[demo] = first_x(demo)
        parts.append(place(demo, n, body, xs[demo]))
    parts.append(END)
    generated = '\n'.join(parts) + '\n'

    text = TABLE.read_text(encoding='utf-8')
    if BEGIN in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END):].lstrip('\n')
    else:
        # The first run replaces the victory quotes written before this tool.
        marker = '\n# Victory quotes (the victory demo'
        head = text[:text.index(marker) + 1] if marker in text else text
        tail = ''
    TABLE.write_text(head.rstrip('\n') + '\n\n' + generated + (('\n' + tail) if tail else ''), encoding='utf-8', newline='\n')
    print(f'{len(items)} entries written to {TABLE.relative_to(ROOT)}')


main()
